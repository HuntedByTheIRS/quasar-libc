/*
 * ── Destruction ────────────────────────────────────────────────────
 */

/*
 * Free all list nodes and reset the struct to zero.
 * The allocator is NOT freed.
 *
 * Safe to call on a zeroed dlist_t (no-op).
 */
void dlist_free(dlist_t *list);

/*
 * ── Inspection ─────────────────────────────────────────────────────
 */

/* Return the number of nodes in the list.  O(1). */
size_t dlist_len(dlist_t list);

/*
 * ── Mutation ───────────────────────────────────────────────────────
 */

/*
 * Insert at the front of the list.  O(1).
 *
 * No-op if list or element is NULL.
 */
void dlist_push_front(dlist_t *list, const void *element);

/*
 * Append to the end of the list.  O(1).
 *
 * No-op if list or element is NULL.
 */
void dlist_push_back(dlist_t *list, const void *element);

/*
 * Remove and copy the front element into out.  O(1).
 *
 * No-op if list is NULL, out is NULL, or the list is empty.
 */
void dlist_pop_front(dlist_t *list, void *out);

/*
 * Remove and copy the back element into out.  O(1).
 *
 * No-op if list is NULL, out is NULL, or the list is empty.
 */
void dlist_pop_back(dlist_t *list, void *out);

/*
 * Insert element before node in the list.  O(1).
 *
 * No-op if list, node, or element is NULL.
 */
void dlist_insert_before(dlist_t *list, DListNode *node,
			 const void *element);

/*
 * Insert element after node in the list.  O(1).
 *
 * No-op if list, node, or element is NULL.
 */
void dlist_insert_after(dlist_t *list, DListNode *node,
			const void *element);

/*
 * Remove node from the list, copying its data into out.  O(1).
 *
 * No-op if list or node is NULL.
 */
void dlist_remove(dlist_t *list, DListNode *node, void *out);

/*
 * Detach all nodes from the list (len = 0).  Node memory is owned
 * by the allocator and reclaimed when the allocator is freed.  O(1).
 */
void dlist_clear(dlist_t *list);

/*
 * ── Node Access ────────────────────────────────────────────────────
 */

/* Return the head node, or NULL if the list is empty. */
DListNode *dlist_head(dlist_t list);

/* Return the tail node, or NULL if the list is empty. */
DListNode *dlist_tail(dlist_t list);

/* Return a pointer to the data stored in node. */
void *dlist_node_data(DListNode *node);

/* Return the successor of node, or NULL if node is the tail. */
DListNode *dlist_node_next(DListNode *node);

/* Return the predecessor of node, or NULL if node is the head. */
DListNode *dlist_node_prev(DListNode *node);

/* ================================================================== */
/*  Ring Buffer                                                        */
/* ================================================================== */

/*
 * ── Creation ───────────────────────────────────────────────────────
 */

/*
 * Create a fixed-capacity ring buffer with the given element size
 * and capacity.  The buffer will never grow; ring_push() returns
 * false when full.
 *
 * Returns a zeroed ring_t if a is NULL or allocation fails.
 */
ring_t ring_new(Allocator *a, size_t element_size, size_t capacity);

/*
 * Create a dynamic ring buffer with the given element size.
 * The buffer grows automatically (by doubling) when full.
 *
 * Returns a zeroed ring_t if a is NULL or allocation fails.
 */
ring_t ring_new_dynamic(Allocator *a, size_t element_size);

/*
 * ── Destruction ────────────────────────────────────────────────────
 */

/*
 * Free the ring buffer's backing storage and reset the struct to
 * zero.  The allocator is NOT freed.
 *
 * Safe to call on a zeroed ring_t (no-op).
 */
void ring_free(ring_t *ring);

/*
 * ── Inspection ─────────────────────────────────────────────────────
 */

/* Return the number of elements currently stored.  O(1). */
size_t ring_len(ring_t ring);

/* Return the maximum number of elements that can be stored.  O(1). */
size_t ring_capacity(ring_t ring);

/* Return true if the buffer contains no elements. */
bool ring_is_empty(ring_t ring);

/* Return true if the buffer is at capacity. */
bool ring_is_full(ring_t ring);

/*
 * ── Operations ─────────────────────────────────────────────────────
 */

/*
 * Push element onto the back of the ring buffer.  The element data
 * is memcpy'd into the buffer.
 *
 * For fixed-capacity buffers: returns false when full.
 * For dynamic buffers: grows automatically, returns false only on
 * allocation failure.
 *
 * No-op and returns false if ring or element is NULL.
 */
bool ring_push(ring_t *ring, const void *element);

/*
 * Pop the front element from the ring buffer, copying it into out.
 *
 * Returns true on success, false if ring is NULL, out is NULL,
 * or the buffer is empty.
 */
bool ring_pop(ring_t *ring, void *out);

/*
 * Return a pointer to the front element (next to be popped).
 * The pointer is invalidated by ring_push() (dynamic buffer growth).
 *
 * Returns NULL if the buffer is empty.
 */
void *ring_front(ring_t ring);

/*
 * Return a pointer to the back element (most recently pushed).
 * The pointer is invalidated by ring_push() (dynamic buffer growth).
 *
 * Returns NULL if the buffer is empty.
 */
void *ring_back(ring_t ring);

/*
 * Remove all elements from the ring buffer (len = 0).
 * Backing storage is retained.
 */
void ring_clear(ring_t *ring);

