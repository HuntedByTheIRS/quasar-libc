/*  Hash Functions                                                     */
/* ================================================================== */

/*
 * Standard hash functions for common types.  These produce a size_t
 * hash value suitable for use with hash tables.  The specific
 * algorithm (FNV-1a) is an implementation detail and may change.
 */

size_t hash_i8(int8_t v);
size_t hash_i16(int16_t v);
size_t hash_i32(int32_t v);
size_t hash_i64(int64_t v);

size_t hash_u8(uint8_t v);
size_t hash_u16(uint16_t v);
size_t hash_u32(uint32_t v);
size_t hash_u64(uint64_t v);

size_t hash_f32(float v);
size_t hash_f64(double v);

size_t hash_str(str_t s);
size_t hash_bytes(const void *data, size_t len);

/* ================================================================== */
/*  Singly Linked List                                                 */
/* ================================================================== */

/*
 * ── Creation ───────────────────────────────────────────────────────
 */

/*
 * Create a new singly linked list with the given element size.
 *
 * Returns a zeroed list_t if a is NULL or allocation fails.
 */
list_t list_new(Allocator *a, size_t element_size);

/*
 * ── Destruction ────────────────────────────────────────────────────
 */

/*
 * Free all list nodes and reset the struct to zero.
 * The allocator is NOT freed.
 *
 * Safe to call on a zeroed list_t (no-op).
 */
void list_free(list_t *list);

/*
 * ── Inspection ─────────────────────────────────────────────────────
 */

/* Return the number of nodes in the list.  O(1). */
size_t list_len(list_t list);

/*
 * ── Mutation ───────────────────────────────────────────────────────
 */

/*
 * Insert element at the front of the list.  O(1).
 * The element data is memcpy'd into the new node.
 *
 * No-op if list or element is NULL.
 */
void list_push_front(list_t *list, const void *element);

/*
 * Append element to the end of the list.  O(1).
 *
 * No-op if list or element is NULL.
 */
void list_push_back(list_t *list, const void *element);

/*
 * Remove and copy the front element into out.  O(1).
 *
 * No-op if list is NULL, out is NULL, or the list is empty.
 */
void list_pop_front(list_t *list, void *out);

/*
 * Remove and copy the back element into out.  O(n) —
 * singly linked lists must traverse to find the predecessor.
 *
 * No-op if list is NULL, out is NULL, or the list is empty.
 */
void list_pop_back(list_t *list, void *out);

/*
 * Detach all nodes from the list (len = 0).  Node memory is owned
 * by the allocator and reclaimed when the allocator is freed.  O(1).
 */
void list_clear(list_t *list);

/*
 * ── Node Access ────────────────────────────────────────────────────
 */

/*
 * Return the head node, or NULL if the list is empty.
 */
ListNode *list_head(list_t list);

/*
 * Return the tail node, or NULL if the list is empty.
 */
ListNode *list_tail(list_t list);

/*
 * Return a pointer to the data stored in node.  The data is owned
 * by the list — do not free it.
 */
void *list_node_data(ListNode *node);

/*
 * Return the successor of node, or NULL if node is the tail.
 */
ListNode *list_node_next(ListNode *node);

/* ================================================================== */
/*  Doubly Linked List                                                 */
/* ================================================================== */

/*
 * ── Creation ───────────────────────────────────────────────────────
 */

/*
 * Create a new doubly linked list with the given element size.
 *
 * Returns a zeroed dlist_t if a is NULL or allocation fails.
 */
